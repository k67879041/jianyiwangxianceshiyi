/*
*********************************************************************************************************
*	函 数 名: MedianFilter
*	功能说明: 中值滤波,计算去除最大值和最小值后的均值
*	形    参: _pStr 数据指针;  _len 数据长度
*	返 回 值: 均值
*********************************************************************************************************
*/
uint16_t MedianFilter( uint16_t *_pStr, uint16_t _len )
{
	uint16_t  i;
  uint16_t  max, min;
	uint32_t  ret ;

	max = _pStr[0];
	min = _pStr[0];

	ret = 0 ;
	for( i = 0 ; i < _len; i++)
	{
		ret += _pStr[i];
		if( max<_pStr[i])	max = _pStr[i] ;
		if( min>_pStr[i])	min = _pStr[i] ;
	}

	ret -= max;
	ret -= min;
	ret /= (_len-2);

	return (uint16_t)ret;
}



