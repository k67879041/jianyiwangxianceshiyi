/*
*********************************************************************************************************
*	函 数 名: SeekMax
*	功能说明: 在指定区域搜索最大值
*	参    数: *p 数据指针		num 数据个数 
*	返 回 值: 计算的绝对值差
*********************************************************************************************************
*/
uint16_t SeekMax( uint16_t *p, uint16_t num )
{
	uint16_t i,lmax=0;
	for(i=0;i<num;i++)	if( p[i]>lmax )	lmax = p[i];
	return lmax;
}


/*
*********************************************************************************************************
*	函 数 名: SeekMin
*	功能说明: 在指定区域搜索最大值
*	参    数: *p 数据指针		num 数据个数 
*	返 回 值: 计算的绝对值差
*********************************************************************************************************
*/
uint16_t SeekMin( uint16_t *p, uint16_t num )
{
	uint16_t i,lmin=0xFFFF;
	for(i=0;i<num;i++)	if( p[i]<lmin )	lmin = p[i];
	return lmin;
}


