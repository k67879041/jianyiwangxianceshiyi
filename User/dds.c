uint8_t	 BuffInterval = 0;		//取点间隔,适用于频率较高时间隔取点
uint16_t DDS_Size;
uint16_t WaveBuffer[2048];


/************************************************
串口输出波形数据
参    数： wave 0正弦,1方波,2锯齿,3三角;
					 fre 频率,单位Hz; amp 幅值,单位mV
************************************************/
void DDS_Set( uint8_t wave, uint32_t fre, int16_t amp )
{
	float ftemp;
	int32_t sltemp;
	const int16_t *p;
	uint16_t i;
	
	// 1. 校验参数
	if( wave>4 )	return;
	if( fre<2 || fre>100000 )	return;
	if( amp>3000 )	return;
	
	// 2. 选择ROM表
	switch( wave )
	{
		case 0:	p = RomSin;	break;
		case 1:	p = RomSquare;	break;
		case 2:	p = RomSawtooth;	break;
		case 3:	p = RomTriangular;	break;
		default :break;
	}
	
	// 3. 计算定时初值-->ftemp
	BuffInterval = 0;
	while(1)
	{
		ftemp = 70312.5f*(BuffInterval+1)/fre;
		if( ftemp>6 && ftemp<65536 )	break;
		else BuffInterval++;
	}
	
	// 4. 复制ROM表
	DDS_Size = 2048/(BuffInterval+1);
	if( 2048%(BuffInterval+1) )	DDS_Size++;	
	for( i=0;i<DDS_Size;i++ ){
		sltemp = p[i*(BuffInterval+1)] * amp / 3300;
		WaveBuffer[i] = (uint16_t)sltemp;	//由32768中心点调整为2048中心点		
	}
	
	DDSTimer->ARR = (uint16_t)(ftemp+0.5f);
	HAL_TIM_Base_Start_IT(&hDDSTimer);
}

void DDS_Stop( void )
{
	HAL_TIM_Base_Stop_IT(&hDDSTimer);
}

